CREATE TABLE instances (
    instance_id text PRIMARY KEY,
    roles       text[] NOT NULL
                CHECK (cardinality(roles) > 0
                       AND roles <@ ARRAY['http', 'worker', 'scheduler', 'retention', 'relay']),
    version     text NOT NULL,
    started_at  timestamptz NOT NULL DEFAULT now(),
    seen_at     timestamptz NOT NULL DEFAULT now(),
    stopped_at  timestamptz NULL
);

CREATE TABLE flows (
    flow_id     text PRIMARY KEY,
    concurrency int NOT NULL DEFAULT 1
                CHECK (concurrency > 0),
    rate        int NULL
                CHECK (rate > 0),
    rate_period int NOT NULL DEFAULT 1
                CHECK (rate_period > 0),
    next_at     timestamptz NULL,
    paused      boolean NOT NULL DEFAULT false
);

CREATE TABLE schedules (
    schedule_id text PRIMARY KEY,
    rule        text NOT NULL,
    tz          text NOT NULL DEFAULT 'UTC',
    next_id     bigint NULL,
    next_at     timestamptz NULL,
    until       timestamptz NULL,
    miss_policy text NOT NULL DEFAULT 'run_once'
                CHECK (miss_policy IN ('skip', 'run_once', 'run_all')),
    paused      boolean NOT NULL DEFAULT false
);

CREATE TABLE jobs (
    id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at  timestamptz NOT NULL DEFAULT now(),
    meta        jsonb NOT NULL,
    headers     jsonb NULL,
    body        bytea NULL,
    key         text NULL,
    schedule_id text NULL REFERENCES schedules ON DELETE SET NULL,
    parent_id   bigint NULL REFERENCES jobs ON DELETE SET NULL
);
CREATE UNIQUE INDEX ux_jobs_key  ON jobs (key) WHERE key IS NOT NULL;
CREATE INDEX ix_jobs_schedule_id ON jobs (schedule_id) WHERE schedule_id IS NOT NULL;
CREATE INDEX ix_jobs_parent_id   ON jobs (parent_id) WHERE parent_id IS NOT NULL;

CREATE TABLE scheduled (
    id       bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    at       timestamptz NOT NULL,
    attempt  int NOT NULL DEFAULT 0
             CHECK (attempt >= 0),
    flow_key text NULL,
    priority int NOT NULL DEFAULT 0
) WITH (
    autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 1000,
    autovacuum_analyze_scale_factor = 0, autovacuum_analyze_threshold = 1000
);
CREATE INDEX ix_scheduled_at ON scheduled (at);

CREATE TABLE enqueued (
    id       bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    attempt  int NOT NULL DEFAULT 0
             CHECK (attempt >= 0),
    at       timestamptz NOT NULL DEFAULT now(),
    flow_key text NULL,
    priority int NOT NULL DEFAULT 0
) WITH (
    autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 1000,
    autovacuum_analyze_scale_factor = 0, autovacuum_analyze_threshold = 1000
);
CREATE INDEX ix_enqueued_candidates ON enqueued (priority DESC, attempt, id)
    WHERE flow_key IS NULL;
CREATE INDEX ix_enqueued_flow       ON enqueued (flow_key, priority DESC, attempt, id)
    WHERE flow_key IS NOT NULL;

CREATE TABLE claimed (
    id          bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    attempt     int NOT NULL,
    flow_key    text NULL,
    priority    int NOT NULL DEFAULT 0,
    instance_id text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now()
) WITH (
    autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 1000,
    autovacuum_analyze_scale_factor = 0, autovacuum_analyze_threshold = 1000
);
CREATE INDEX ix_claimed_flow        ON claimed (flow_key) WHERE flow_key IS NOT NULL;
CREATE INDEX ix_claimed_instance_id ON claimed (instance_id);
CREATE INDEX ix_claimed_at          ON claimed (at);

CREATE TABLE processed (
    id          bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    attempt     int NOT NULL,
    instance_id text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    status      text NOT NULL
                CHECK (status IN ('completed', 'failed', 'cancelled')),
    outcome     jsonb NULL,
    headers     jsonb NULL,
    body        bytea NULL
);
CREATE INDEX ix_processed_at        ON processed (at);
CREATE INDEX ix_processed_status_id ON processed (status, id DESC);

CREATE TABLE history (
    seq         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id          bigint NOT NULL REFERENCES jobs ON DELETE CASCADE,
    attempt     int NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    kind        text NOT NULL
                CHECK (kind IN ('scheduled', 'enqueued', 'claimed', 'released', 'retried',
                                'completed', 'failed', 'cancelled', 'callback')),
    instance_id text NULL,
    message     text NULL
);
CREATE INDEX ix_history_id_seq ON history (id, seq);

CREATE TABLE stats (
    name  text PRIMARY KEY,
    value bigint NOT NULL,
    at    timestamptz NOT NULL
) WITH (fillfactor = 50);

CREATE FUNCTION enqueue_v1(job jsonb) RETURNS bigint
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_sink     text := job->>'sink';
    v_retry    text := coalesce(job->>'retry', 'none');
    v_flow     text := nullif(job->>'flow_key', '');
    v_key      text := nullif(job->>'key', '');
    v_priority int;
    v_timeout  int;
    v_body     bytea;
    v_headers  jsonb := nullif(job->'headers', 'null'::jsonb);
    v_at       timestamptz;
    v_meta     jsonb;
    v_error    text;
    new_id     bigint;
BEGIN
    v_error := CASE
        WHEN jsonb_typeof(job) IS DISTINCT FROM 'object'
            THEN 'must be a JSON object'
        WHEN coalesce(v_sink, '') NOT IN ('http', 'noop')
            THEN 'sink must be http or noop'
        WHEN v_sink = 'http' AND (coalesce(job->>'url', '') !~* '^https?://[^/?#[:space:]]+'
                                  OR job->>'url' ~ '[[:space:][:cntrl:]]')
            THEN 'url must be an http or https URL without spaces'
        WHEN v_sink = 'http' AND coalesce(job->>'method', 'POST') !~* '^[a-z]{1,16}$'
            THEN 'method must be an HTTP method'
        WHEN jsonb_typeof(job->'headers') NOT IN ('object', 'null')
            THEN 'headers must be an object'
        WHEN EXISTS (SELECT 1
                     FROM jsonb_each(coalesce(nullif(job->'headers', 'null'::jsonb), '{}')) h
                     WHERE jsonb_typeof(h.value) <> 'string')
            THEN 'header values must be strings'
        WHEN jsonb_typeof(job->'body') = 'string' AND jsonb_typeof(job->'body_base64') = 'string'
            THEN 'body and body_base64 are exclusive'
        WHEN v_key !~ '^[^[:cntrl:]]{1,255}$'
            THEN 'key must be 1 to 255 characters without control characters'
        WHEN v_flow !~ '^[a-z0-9][a-z0-9._:-]{0,127}$'
            THEN 'flow_key must be 1 to 128 characters of a-z, 0-9, . _ : - and start with a letter or a digit'
        WHEN job->>'priority' !~ '^-?[0-9]{1,10}$'
            THEN 'priority must be an integer'
        WHEN (job->>'priority')::bigint NOT BETWEEN -2147483648 AND 2147483647
            THEN 'priority must be from -2147483648 to 2147483647'
        WHEN job->>'timeout' !~ '^[1-9][0-9]{0,8}$'
            THEN 'timeout must be a positive number of milliseconds'
        WHEN v_retry NOT IN ('none', 'fixed', 'fibonacci', 'exponential')
            THEN 'retry must be none, fixed, fibonacci or exponential'
        WHEN coalesce(job->>'retry_count', CASE WHEN v_retry <> 'none' THEN '' END) !~ '^[0-9]{1,4}$'
            THEN 'retry_count must be a number up to 9999'
        WHEN coalesce(job->>'retry_delay', CASE WHEN v_retry IN ('fibonacci', 'exponential') THEN '' END) !~ '^[0-9]{1,5}$'
            THEN 'retry_delay must be a number of seconds up to 99999'
        WHEN job->>'retry_max_delay' !~ '^[0-9]{1,5}$'
            THEN 'retry_max_delay must be a number of seconds up to 99999'
        WHEN job->>'at' IS NOT NULL AND job->>'delay' IS NOT NULL
            THEN 'at and delay are exclusive'
        WHEN job->>'at' !~ '^[0-9]{1,12}$'
            THEN 'at must be a unix time in seconds'
        WHEN job->>'delay' !~ '^[0-9]{1,9}$'
            THEN 'delay must be a number of seconds'
    END;
    IF v_error IS NOT NULL THEN
        RAISE EXCEPTION 'invalid job: %', v_error USING ERRCODE = 'invalid_parameter_value';
    END IF;

    v_priority := coalesce((job->>'priority')::int, 0);
    v_timeout  := (job->>'timeout')::int;
    v_body     := nullif(CASE
                      WHEN jsonb_typeof(job->'body') = 'string' THEN convert_to(job->>'body', 'UTF8')
                      WHEN jsonb_typeof(job->'body') NOT IN ('string', 'null') THEN convert_to((job->'body')::text, 'UTF8')
                      WHEN jsonb_typeof(job->'body_base64') = 'string' THEN decode(job->>'body_base64', 'base64')
                  END, ''::bytea);
    v_at       := CASE
                      WHEN job->>'at' IS NOT NULL THEN to_timestamp((job->>'at')::bigint)
                      WHEN job->>'delay' IS NOT NULL THEN clock_timestamp() + make_interval(secs => (job->>'delay')::int)
                  END;
    IF v_at <= clock_timestamp() THEN
        v_at := NULL;
    END IF;

    v_meta := jsonb_strip_nulls(jsonb_build_object(
        'sink', v_sink,
        'method', CASE WHEN v_sink = 'http' THEN upper(coalesce(job->>'method', 'POST')) END,
        'url', CASE WHEN v_sink = 'http' THEN job->>'url' END,
        'retry', nullif(v_retry, 'none'),
        'retry_count', CASE WHEN v_retry <> 'none' THEN (job->>'retry_count')::int END,
        'retry_delay', CASE WHEN v_retry <> 'none' THEN coalesce((job->>'retry_delay')::int, 0) END,
        'retry_max_delay', CASE WHEN v_retry IN ('fibonacci', 'exponential') THEN (job->>'retry_max_delay')::int END,
        'timeout', v_timeout,
        'flow_key', v_flow,
        'priority', nullif(v_priority, 0),
        'traceparent', job->>'traceparent',
        'tracestate', job->>'tracestate'));

    IF jsonb_typeof(job->'body') NOT IN ('string', 'null')
       AND NOT EXISTS (SELECT 1 FROM jsonb_object_keys(coalesce(v_headers, '{}')) k
                       WHERE lower(k) = 'content-type') THEN
        v_headers := coalesce(v_headers, '{}') || '{"content-type": "application/json"}';
    END IF;

    INSERT INTO jobs (meta, headers, body, key)
    VALUES (v_meta, v_headers, v_body, v_key)
    ON CONFLICT (key) WHERE key IS NOT NULL DO NOTHING
    RETURNING jobs.id INTO new_id;
    IF new_id IS NULL THEN
        RETURN (SELECT j.id FROM jobs j WHERE j.key = v_key);
    END IF;

    IF v_at IS NULL THEN
        INSERT INTO enqueued (id, flow_key, priority) VALUES (new_id, v_flow, v_priority);
        INSERT INTO history (id, attempt, kind) VALUES (new_id, 0, 'enqueued');
    ELSE
        INSERT INTO scheduled (id, at, flow_key, priority) VALUES (new_id, v_at, v_flow, v_priority);
        INSERT INTO history (id, attempt, kind) VALUES (new_id, 0, 'scheduled');
    END IF;
    RETURN new_id;
END $$;

CREATE FUNCTION promote_v1(p_instance_id text, p_limit int) RETURNS int
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    n int;
BEGIN
    WITH d AS (
        DELETE FROM scheduled
        WHERE id IN (SELECT s.id
                     FROM scheduled s
                     WHERE s.at <= now()
                     ORDER BY s.at, s.id
                     LIMIT p_limit
                     FOR UPDATE SKIP LOCKED)
        RETURNING id, attempt, at, flow_key, priority
    ), b AS (
        INSERT INTO enqueued (id, attempt, at, flow_key, priority)
        SELECT * FROM d
        RETURNING id, attempt
    ), hist AS (
        INSERT INTO history (id, attempt, kind, instance_id)
        SELECT b.id, b.attempt, 'enqueued', p_instance_id
        FROM b
    )
    SELECT count(*) INTO n FROM b;
    RETURN n;
END $$;

CREATE FUNCTION refresh_stats_v1(p_max_age interval DEFAULT interval '2 seconds') RETURNS boolean
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NOT pg_try_advisory_xact_lock(hashtextextended(current_schema() || '#stats', 0)) THEN
        RETURN false;
    END IF;
    IF EXISTS (SELECT 1 FROM stats WHERE name = 'enqueued' AND at > clock_timestamp() - p_max_age) THEN
        RETURN false;
    END IF;

    INSERT INTO stats (name, value, at)
    SELECT v.name, v.value, clock_timestamp()
    FROM (SELECT count(*) AS n, min(at) AS due
          FROM enqueued) AS e,
         (SELECT count(*) AS n, count(*) FILTER (WHERE status = 'failed') AS failed
          FROM processed
          WHERE at > now() - interval '24 hours') AS p,
         LATERAL (VALUES
            ('scheduled', (SELECT count(*) FROM scheduled)),
            ('enqueued',  e.n),
            ('claimed',   (SELECT count(*) FROM claimed)),
            ('lag_seconds',
                (SELECT coalesce(floor(extract(epoch FROM clock_timestamp() - min(d.at))), 0)::bigint
                 FROM (SELECT e.due AS at
                       UNION ALL
                       SELECT min(s.at) FROM scheduled s WHERE s.at <= clock_timestamp()) d)),
            ('processed_24h', p.n),
            ('failed_24h', p.failed),
            ('instances', (SELECT count(*) FROM instances i WHERE i.stopped_at IS NULL))
         ) AS v(name, value)
    ON CONFLICT (name) DO UPDATE SET value = EXCLUDED.value, at = EXCLUDED.at;
    RETURN true;
END $$;

CREATE FUNCTION claim_plain_v1(p_instance_id text, p_limit int)
RETURNS TABLE (
    id          bigint,
    meta        jsonb,
    headers     jsonb,
    body        bytea,
    schedule_id text,
    key         text,
    attempt     int
)
LANGUAGE sql SET search_path FROM CURRENT AS $$
    WITH b AS (
        DELETE FROM enqueued
        WHERE id IN (SELECT e.id
                     FROM enqueued AS e
                     WHERE e.flow_key IS NULL
                     ORDER BY e.priority DESC, e.attempt, e.id
                     LIMIT p_limit
                     FOR UPDATE SKIP LOCKED)
        RETURNING id, attempt, priority
    ), hist AS (
        INSERT INTO history (id, attempt, kind, instance_id)
        SELECT b.id, b.attempt, 'claimed', p_instance_id FROM b
    ), c AS (
        INSERT INTO claimed (id, attempt, priority, instance_id)
        SELECT b.id, b.attempt, b.priority, p_instance_id FROM b
        RETURNING claimed.id, claimed.attempt, claimed.priority
    )
    SELECT j.id, j.meta, j.headers, j.body, j.schedule_id, j.key, c.attempt
    FROM c
    INNER JOIN jobs AS j ON j.id = c.id
    ORDER BY c.priority DESC, c.attempt, c.id
$$;

CREATE FUNCTION flow_rate_free_v1(p_rate int, p_period int, p_next_at timestamptz)
RETURNS int
LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT CASE
        WHEN p_rate IS NULL THEN 2147483647
        ELSE floor(greatest(p_period - greatest(extract(epoch FROM p_next_at - now()), 0), 0)
                   * p_rate / p_period)::int
    END
$$;

CREATE FUNCTION claim_flow_v1(p_instance_id text, p_limit int)
RETURNS TABLE (
    id          bigint,
    meta        jsonb,
    headers     jsonb,
    body        bytea,
    schedule_id text,
    key         text,
    attempt     int
)
LANGUAGE plpgsql SET search_path FROM CURRENT SET jit = off AS $$
#variable_conflict use_column
DECLARE
    v_flows text[];
BEGIN
    WITH RECURSIVE names(flow_key) AS (
        (SELECT e.flow_key FROM enqueued e WHERE e.flow_key IS NOT NULL ORDER BY e.flow_key LIMIT 1)
        UNION ALL
        SELECT (SELECT e.flow_key FROM enqueued e WHERE e.flow_key > names.flow_key ORDER BY e.flow_key LIMIT 1)
        FROM names
        WHERE names.flow_key IS NOT NULL
    ), ready AS MATERIALIZED (
        SELECT names.flow_key
        FROM names
        LEFT JOIN flows f ON f.flow_id = names.flow_key
        WHERE names.flow_key IS NOT NULL
          AND NOT coalesce(f.paused, false)
          AND flow_rate_free_v1(f.rate, f.rate_period, f.next_at) >= 1
          AND (SELECT count(*) FROM claimed c WHERE c.flow_key = names.flow_key) < coalesce(f.concurrency, 1)
    )
    SELECT coalesce(array_agg(l.flow_key), '{}')
    INTO v_flows
    FROM (SELECT ready.flow_key
          FROM ready
          WHERE pg_try_advisory_xact_lock(hashtextextended(current_schema() || ':' || ready.flow_key, 0))
          LIMIT p_limit) l;

    RETURN QUERY
    WITH a AS (
        SELECT x.id
        FROM unnest(v_flows) AS u(name)
        LEFT JOIN flows f ON f.flow_id = u.name
        CROSS JOIN LATERAL (
            SELECT e.id
            FROM enqueued e
            WHERE e.flow_key = u.name
            ORDER BY e.priority DESC, e.attempt, e.id
            LIMIT least(greatest(coalesce(f.concurrency, 1)
                                 - (SELECT count(*) FROM claimed cl WHERE cl.flow_key = u.name), 0),
                        flow_rate_free_v1(f.rate, f.rate_period, f.next_at))
        ) x
        ORDER BY x.id
        LIMIT p_limit
    ), b AS (
        DELETE FROM enqueued WHERE id IN (SELECT a.id FROM a) RETURNING id, attempt, flow_key, priority
    ), hist AS (
        INSERT INTO history (id, attempt, kind, instance_id)
        SELECT b.id, b.attempt, 'claimed', p_instance_id FROM b
    ), rated AS (
        UPDATE flows f
        SET next_at = greatest(f.next_at, now()) + make_interval(secs => f.rate_period::float8 * y.n / f.rate)
        FROM (SELECT b.flow_key, count(*) AS n FROM b GROUP BY b.flow_key) y
        WHERE f.flow_id = y.flow_key AND f.rate IS NOT NULL
    ), c AS (
        INSERT INTO claimed (id, attempt, flow_key, priority, instance_id)
        SELECT b.id, b.attempt, b.flow_key, b.priority, p_instance_id FROM b
        RETURNING claimed.id, claimed.attempt, claimed.priority
    )
    SELECT j.id, j.meta, j.headers, j.body, j.schedule_id, j.key, c.attempt
    FROM c
    INNER JOIN jobs AS j ON j.id = c.id
    ORDER BY c.priority DESC, c.attempt, c.id;
END $$;

CREATE FUNCTION claim_v1(p_instance_id text, p_limit int)
RETURNS TABLE (
    id          bigint,
    meta        jsonb,
    headers     jsonb,
    body        bytea,
    schedule_id text,
    key         text,
    attempt     int
)
LANGUAGE plpgsql SET search_path FROM CURRENT SET jit = off AS $$
DECLARE
    v_plain bigint;
BEGIN
    RETURN QUERY SELECT * FROM claim_plain_v1(p_instance_id, p_limit);
    GET DIAGNOSTICS v_plain = ROW_COUNT;
    IF v_plain < p_limit THEN
        RETURN QUERY SELECT * FROM claim_flow_v1(p_instance_id, p_limit - v_plain::int);
    END IF;
END $$;
