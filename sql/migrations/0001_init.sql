CREATE TABLE instances (
    instance_id text PRIMARY KEY,
    roles       text[] NOT NULL
                CHECK (cardinality(roles) > 0
                       AND roles <@ ARRAY['http', 'worker', 'scheduler', 'retention', 'relay']),
    version     text NOT NULL,
    started_at  timestamptz NOT NULL DEFAULT now(),
    seen_at     timestamptz NOT NULL DEFAULT now(),
    stopped_at  timestamptz NULL
);

CREATE TABLE flows (
    flow_id     text PRIMARY KEY,
    concurrency int NOT NULL DEFAULT 1
                CHECK (concurrency > 0),
    rate        int NULL
                CHECK (rate > 0),
    rate_period int NOT NULL DEFAULT 1
                CHECK (rate_period > 0),
    next_at     timestamptz NULL,
    paused      boolean NOT NULL DEFAULT false
);

CREATE TABLE schedules (
    schedule_id text PRIMARY KEY,
    rule        text NOT NULL,
    tz          text NOT NULL DEFAULT 'UTC',
    next_id     bigint NULL,
    next_at     timestamptz NULL,
    until       timestamptz NULL,
    miss_policy text NOT NULL DEFAULT 'run_once'
                CHECK (miss_policy IN ('skip', 'run_once', 'run_all')),
    paused      boolean NOT NULL DEFAULT false
);

CREATE TABLE jobs (
    id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at  timestamptz NOT NULL DEFAULT now(),
    meta        jsonb NOT NULL,
    headers     jsonb NULL,
    body        bytea NULL,
    key         text NULL,
    schedule_id text NULL REFERENCES schedules ON DELETE SET NULL,
    parent_id   bigint NULL REFERENCES jobs ON DELETE SET NULL
);
CREATE UNIQUE INDEX ux_jobs_key  ON jobs (key) WHERE key IS NOT NULL;
CREATE INDEX ix_jobs_schedule_id ON jobs (schedule_id) WHERE schedule_id IS NOT NULL;
CREATE INDEX ix_jobs_parent_id   ON jobs (parent_id, id) WHERE parent_id IS NOT NULL;

CREATE TABLE scheduled (
    id       bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    at       timestamptz NOT NULL,
    attempt  int NOT NULL DEFAULT 0
             CHECK (attempt >= 0),
    flow_key text NULL,
    priority int NOT NULL DEFAULT 0
) WITH (
    autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 1000,
    autovacuum_analyze_scale_factor = 0, autovacuum_analyze_threshold = 1000
);
CREATE INDEX ix_scheduled_at ON scheduled (at);

CREATE TABLE enqueued (
    id       bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    attempt  int NOT NULL DEFAULT 0
             CHECK (attempt >= 0),
    at       timestamptz NOT NULL DEFAULT now(),
    flow_key text NULL,
    priority int NOT NULL DEFAULT 0
) WITH (
    autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 1000,
    autovacuum_analyze_scale_factor = 0, autovacuum_analyze_threshold = 1000
);
CREATE INDEX ix_enqueued_candidates ON enqueued (priority DESC, attempt, id)
    WHERE flow_key IS NULL;
CREATE INDEX ix_enqueued_flow       ON enqueued (flow_key, priority DESC, attempt, id)
    WHERE flow_key IS NOT NULL;

CREATE TABLE claimed (
    id          bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    attempt     int NOT NULL,
    flow_key    text NULL,
    priority    int NOT NULL DEFAULT 0,
    instance_id text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now()
) WITH (
    autovacuum_vacuum_scale_factor = 0, autovacuum_vacuum_threshold = 1000,
    autovacuum_analyze_scale_factor = 0, autovacuum_analyze_threshold = 1000
);
CREATE INDEX ix_claimed_flow        ON claimed (flow_key) WHERE flow_key IS NOT NULL;
CREATE INDEX ix_claimed_instance_id ON claimed (instance_id);
CREATE INDEX ix_claimed_at          ON claimed (at);

CREATE TABLE processed (
    id          bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    attempt     int NOT NULL,
    instance_id text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    status      text NOT NULL
                CHECK (status IN ('completed', 'failed', 'cancelled')),
    outcome     jsonb NULL,
    headers     jsonb NULL,
    body        bytea NULL
);
CREATE INDEX ix_processed_at        ON processed (at);
CREATE INDEX ix_processed_status_id ON processed (status, id DESC);

CREATE TABLE history (
    seq         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id          bigint NOT NULL REFERENCES jobs ON DELETE CASCADE,
    attempt     int NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    kind        text NOT NULL
                CHECK (kind IN ('scheduled', 'enqueued', 'claimed', 'released', 'retried',
                                'completed', 'failed', 'cancelled', 'callback')),
    instance_id text NULL,
    message     text NULL
);
CREATE INDEX ix_history_id_seq ON history (id, seq);

CREATE TABLE stats (
    name  text PRIMARY KEY,
    value bigint NOT NULL,
    at    timestamptz NOT NULL
) WITH (fillfactor = 50);

CREATE FUNCTION enqueue_v1(job jsonb) RETURNS bigint
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    c_job_fields CONSTANT text[] := ARRAY['method', 'url', 'retry', 'timeout', 'flow_key',
                           'priority', 'headers', 'body', 'body_base64', 'at', 'delay', 'key',
                           'callback', 'traceparent', 'tracestate'];
    c_cb_fields CONSTANT text[] := ARRAY['url', 'method', 'mode', 'types', 'headers', 'retry',
                           'timeout', 'flow_key', 'priority'];
    c_retry_fields CONSTANT text[] := ARRAY['policy', 'count', 'delay', 'max_delay'];
    c_flow CONSTANT text := '^[a-z0-9][a-z0-9._:-]{0,127}$';
    c_url CONSTANT text := '^https?://([a-z0-9._~%!$&''()*+,;=:-]+@)?([a-z0-9._-]+|\[[0-9a-f:.]+\])(:[0-9]{1,5})?'
                           '([/?#][]a-z0-9._~%!$&''()*+,;=:@/?#[-]*)?$';
    v_sink     text := CASE WHEN job->>'url' ~* '^noop:' THEN 'noop' ELSE 'http' END;
    v_retry    jsonb := nullif(job->'retry', 'null'::jsonb);
    v_policy   text := v_retry->>'policy';
    v_flow     text := nullif(job->>'flow_key', '');
    v_key      text := nullif(job->>'key', '');
    v_priority int;
    v_timeout  int;
    v_body     bytea;
    v_headers  jsonb := nullif(job->'headers', 'null'::jsonb);
    v_at       timestamptz;
    v_meta     jsonb;
    v_error    text;
    new_id     bigint;
    v_cb       jsonb := nullif(job->'callback', 'null'::jsonb);
    v_cb_url   text := v_cb->>'url';
    v_cb_mode  text := coalesce(v_cb->>'mode', 'webhook');
    v_cb_method text := upper(v_cb->>'method');
    v_cb_retry jsonb := nullif(v_cb->'retry', 'null'::jsonb);
    v_cb_policy text := v_cb_retry->>'policy';
    v_cb_flow  text := nullif(v_cb->>'flow_key', '');
    v_callback jsonb;
BEGIN
    v_error := CASE
        WHEN jsonb_typeof(job) IS DISTINCT FROM 'object'
            THEN 'must be a JSON object'
        WHEN EXISTS (SELECT 1 FROM jsonb_object_keys(job) k WHERE k <> ALL (c_job_fields))
            THEN 'fields that are not known: '
                 || (SELECT string_agg(k, ', ' ORDER BY k)
                     FROM jsonb_object_keys(job) k WHERE k <> ALL (c_job_fields))
        WHEN v_sink = 'http' AND coalesce(job->>'url', '') !~* c_url
            THEN 'url must be an http or https URL of URL characters only (percent-encode the others)'
        WHEN v_sink = 'http' AND coalesce(job->>'method', 'POST') !~* '^[a-z]{1,16}$'
            THEN 'method must be an HTTP method'
        WHEN jsonb_typeof(job->'headers') NOT IN ('object', 'null')
            THEN 'headers must be an object'
        WHEN EXISTS (SELECT 1
                     FROM jsonb_each(coalesce(nullif(job->'headers', 'null'::jsonb), '{}')) h
                     WHERE jsonb_typeof(h.value) <> 'string')
            THEN 'header values must be strings'
        WHEN jsonb_typeof(job->'body') <> 'null' AND jsonb_typeof(job->'body_base64') <> 'null'
            THEN 'body and body_base64 are exclusive'
        WHEN jsonb_typeof(job->'body_base64') NOT IN ('string', 'null')
            THEN 'body_base64 must be a string'
        WHEN v_key !~ '^[^[:cntrl:]]{1,255}$'
            THEN 'key must be 1 to 255 characters without control characters'
        WHEN v_flow !~ c_flow
            THEN 'flow_key must be 1 to 128 characters of a-z, 0-9, . _ : - and start with a letter or a digit'
        WHEN job->>'priority' !~ '^-?[0-9]{1,10}$'
            THEN 'priority must be an integer'
        WHEN (job->>'priority')::bigint NOT BETWEEN -2147483648 AND 2147483647
            THEN 'priority must be from -2147483648 to 2147483647'
        WHEN job->>'timeout' !~ '^[1-9][0-9]{0,8}$'
            THEN 'timeout must be a positive number of milliseconds'
        WHEN jsonb_typeof(v_retry) <> 'object'
            THEN 'retry must be an object'
        WHEN v_retry IS NOT NULL AND coalesce(v_policy, '') NOT IN ('fixed', 'fibonacci', 'exponential')
            THEN 'retry.policy must be fixed, fibonacci or exponential'
        WHEN EXISTS (SELECT 1 FROM jsonb_object_keys(v_retry) k WHERE k <> ALL (c_retry_fields))
            THEN 'retry may have policy, count, delay and max_delay only'
        WHEN v_retry IS NOT NULL AND CASE
                WHEN jsonb_typeof(v_retry->'count') = 'number' AND v_retry->>'count' ~ '^[0-9]{1,4}$'
                    THEN (v_retry->>'count')::int > 9999
                ELSE true END
            THEN 'retry.count must be a number up to 9999'
        WHEN CASE
                WHEN coalesce(jsonb_typeof(v_retry->'delay'), 'null') = 'null'
                    THEN v_policy IN ('fibonacci', 'exponential')
                WHEN jsonb_typeof(v_retry->'delay') = 'number' AND v_retry->>'delay' ~ '^[0-9]{1,7}$'
                    THEN (v_retry->>'delay')::bigint > 604800
                ELSE true END
            THEN 'retry.delay must be a number of seconds up to 604800'
        WHEN CASE
                WHEN coalesce(jsonb_typeof(v_retry->'max_delay'), 'null') = 'null' THEN false
                WHEN jsonb_typeof(v_retry->'max_delay') = 'number' AND v_retry->>'max_delay' ~ '^[0-9]{1,7}$'
                    THEN (v_retry->>'max_delay')::bigint > 604800
                ELSE true END
            THEN 'retry.max_delay must be a number of seconds up to 604800'
        WHEN v_policy = 'fixed' AND v_retry->'max_delay' IS NOT NULL
            THEN 'retry.max_delay is for fibonacci and exponential'
        WHEN job->>'at' IS NOT NULL AND job->>'delay' IS NOT NULL
            THEN 'at and delay are exclusive'
        WHEN job->>'at' !~ '^([0-9]{1,12}|[0-9]{4}-[0-9]{2}-[0-9]{2}[Tt][0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]+)?([Zz]|[+-][0-9]{2}:[0-9]{2}))$'
            THEN 'at must be an RFC 3339 time or unix seconds'
        WHEN job->>'delay' !~ '^[0-9]{1,9}$'
            THEN 'delay must be a number of seconds'
        WHEN jsonb_typeof(job->'callback') NOT IN ('object', 'null')
            THEN 'callback must be an object'
        WHEN EXISTS (SELECT 1 FROM jsonb_object_keys(v_cb) k WHERE k <> ALL (c_cb_fields))
            THEN 'callback fields that are not known: '
                 || (SELECT string_agg(k, ', ' ORDER BY k)
                     FROM jsonb_object_keys(v_cb) k WHERE k <> ALL (c_cb_fields))
        WHEN v_cb IS NOT NULL AND coalesce(v_cb_url, '') !~* c_url
            THEN 'callback.url must be an http or https URL of URL characters only (percent-encode the others)'
        WHEN v_cb_mode NOT IN ('webhook', 'relay')
            THEN 'callback.mode must be webhook or relay'
        WHEN v_cb_method NOT IN ('POST', 'PUT')
            THEN 'callback.method must be POST or PUT'
        WHEN jsonb_typeof(v_cb->'types') NOT IN ('array', 'null')
            THEN 'callback.types must be an array'
        WHEN jsonb_typeof(v_cb->'types') = 'array'
             AND (jsonb_array_length(v_cb->'types') = 0
                  OR EXISTS (SELECT 1 FROM jsonb_array_elements(v_cb->'types') t
                             WHERE t.value NOT IN ('"irisqo.job.completed"'::jsonb,
                                                   '"irisqo.job.failed"'::jsonb,
                                                   '"irisqo.job.cancelled"'::jsonb)))
            THEN 'callback.types must list irisqo.job.completed, irisqo.job.failed or irisqo.job.cancelled'
        WHEN jsonb_typeof(v_cb->'headers') NOT IN ('object', 'null')
            THEN 'callback.headers must be an object'
        WHEN EXISTS (SELECT 1
                     FROM jsonb_each(coalesce(nullif(v_cb->'headers', 'null'::jsonb), '{}')) h
                     WHERE jsonb_typeof(h.value) <> 'string')
            THEN 'callback.headers values must be strings'
        WHEN v_cb_flow !~ c_flow
            THEN 'callback.flow_key must be 1 to 128 characters of a-z, 0-9, . _ : - and start with a letter or a digit'
        WHEN v_cb->>'priority' !~ '^-?[0-9]{1,10}$'
            THEN 'callback.priority must be an integer'
        WHEN (v_cb->>'priority')::bigint NOT BETWEEN -2147483648 AND 2147483647
            THEN 'callback.priority must be from -2147483648 to 2147483647'
        WHEN v_cb->>'timeout' !~ '^[1-9][0-9]{0,8}$'
            THEN 'callback.timeout must be a positive number of milliseconds'
        WHEN jsonb_typeof(v_cb_retry) <> 'object'
            THEN 'callback.retry must be an object'
        WHEN v_cb_retry IS NOT NULL AND coalesce(v_cb_policy, '') NOT IN ('fixed', 'fibonacci', 'exponential')
            THEN 'callback.retry.policy must be fixed, fibonacci or exponential'
        WHEN EXISTS (SELECT 1 FROM jsonb_object_keys(v_cb_retry) k WHERE k <> ALL (c_retry_fields))
            THEN 'callback.retry may have policy, count, delay and max_delay only'
        WHEN v_cb_retry IS NOT NULL AND CASE
                WHEN jsonb_typeof(v_cb_retry->'count') = 'number' AND v_cb_retry->>'count' ~ '^[0-9]{1,4}$'
                    THEN (v_cb_retry->>'count')::int > 9999
                ELSE true END
            THEN 'callback.retry.count must be a number up to 9999'
        WHEN CASE
                WHEN coalesce(jsonb_typeof(v_cb_retry->'delay'), 'null') = 'null'
                    THEN v_cb_policy IN ('fibonacci', 'exponential')
                WHEN jsonb_typeof(v_cb_retry->'delay') = 'number' AND v_cb_retry->>'delay' ~ '^[0-9]{1,7}$'
                    THEN (v_cb_retry->>'delay')::bigint > 604800
                ELSE true END
            THEN 'callback.retry.delay must be a number of seconds up to 604800'
        WHEN CASE
                WHEN coalesce(jsonb_typeof(v_cb_retry->'max_delay'), 'null') = 'null' THEN false
                WHEN jsonb_typeof(v_cb_retry->'max_delay') = 'number' AND v_cb_retry->>'max_delay' ~ '^[0-9]{1,7}$'
                    THEN (v_cb_retry->>'max_delay')::bigint > 604800
                ELSE true END
            THEN 'callback.retry.max_delay must be a number of seconds up to 604800'
        WHEN v_cb_policy = 'fixed' AND v_cb_retry->'max_delay' IS NOT NULL
            THEN 'callback.retry.max_delay is for fibonacci and exponential'
    END;
    IF v_error IS NOT NULL THEN
        RAISE EXCEPTION 'invalid job: %', v_error USING ERRCODE = 'invalid_parameter_value';
    END IF;
    v_priority := coalesce((job->>'priority')::int, 0);
    v_timeout  := (job->>'timeout')::int;
    v_body     := nullif(CASE
                      WHEN jsonb_typeof(job->'body') = 'string' THEN convert_to(job->>'body', 'UTF8')
                      WHEN jsonb_typeof(job->'body') NOT IN ('string', 'null') THEN convert_to((job->'body')::text, 'UTF8')
                      WHEN jsonb_typeof(job->'body_base64') = 'string' THEN decode(job->>'body_base64', 'base64')
                  END, ''::bytea);
    BEGIN
        v_at := CASE
                    WHEN job->>'at' ~ '^[0-9]+$' THEN to_timestamp((job->>'at')::bigint)
                    WHEN job->>'at' IS NOT NULL THEN (job->>'at')::timestamptz
                    WHEN job->>'delay' IS NOT NULL THEN clock_timestamp() + make_interval(secs => (job->>'delay')::int)
                END;
    EXCEPTION WHEN datetime_field_overflow OR invalid_datetime_format THEN
        v_at := '-infinity';
    END;
    IF v_at < 'epoch'::timestamptz OR v_at >= '10000-01-01T00:00:00Z'::timestamptz THEN
        RAISE EXCEPTION 'invalid job: at must be an RFC 3339 time or unix seconds from 1970 to 9999'
            USING ERRCODE = 'invalid_parameter_value';
    END IF;
    IF v_at <= clock_timestamp() THEN
        v_at := NULL;
    END IF;
    IF v_cb IS NOT NULL THEN
        v_callback := jsonb_strip_nulls(jsonb_build_object(
            'url', v_cb_url,
            'method', v_cb_method,
            'mode', v_cb_mode,
            'types', nullif(v_cb->'types', 'null'::jsonb),
            'headers', nullif(v_cb->'headers', 'null'::jsonb),
            'retry', v_cb_retry,
            'timeout', (v_cb->>'timeout')::int,
            'flow_key', v_cb_flow,
            'priority', nullif(coalesce((v_cb->>'priority')::int, 0), 0)));
    END IF;
    v_meta := jsonb_strip_nulls(jsonb_build_object(
        'sink', v_sink,
        'method', CASE WHEN v_sink = 'http' THEN upper(coalesce(job->>'method', 'POST')) END,
        'url', CASE WHEN v_sink = 'http' THEN job->>'url' END,
        'retry', v_retry,
        'timeout', v_timeout,
        'flow_key', v_flow,
        'priority', nullif(v_priority, 0),
        'traceparent', job->>'traceparent',
        'tracestate', job->>'tracestate',
        'callback', v_callback));
    IF jsonb_typeof(job->'body') NOT IN ('string', 'null')
       AND NOT EXISTS (SELECT 1 FROM jsonb_object_keys(coalesce(v_headers, '{}')) k
                       WHERE lower(k) = 'content-type') THEN
        v_headers := coalesce(v_headers, '{}') || '{"content-type": "application/json"}';
    END IF;
    INSERT INTO jobs (meta, headers, body, key)
    VALUES (v_meta, v_headers, v_body, v_key)
    ON CONFLICT (key) WHERE key IS NOT NULL DO NOTHING
    RETURNING jobs.id INTO new_id;
    IF new_id IS NULL THEN
        RETURN (SELECT j.id FROM jobs j WHERE j.key = v_key);
    END IF;
    IF v_at IS NULL THEN
        INSERT INTO enqueued (id, flow_key, priority) VALUES (new_id, v_flow, v_priority);
        INSERT INTO history (id, attempt, kind) VALUES (new_id, 0, 'enqueued');
    ELSE
        INSERT INTO scheduled (id, at, flow_key, priority) VALUES (new_id, v_at, v_flow, v_priority);
        INSERT INTO history (id, attempt, kind) VALUES (new_id, 0, 'scheduled');
    END IF;
    RETURN new_id;
END $$;

CREATE FUNCTION promote_v1(p_instance_id text, p_limit int) RETURNS int
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    n int;
BEGIN
    WITH d AS (
        DELETE FROM scheduled
        WHERE id = ANY(ARRAY(SELECT s.id
                             FROM scheduled s
                             WHERE s.at <= now()
                             ORDER BY s.at, s.id
                             LIMIT p_limit
                             FOR UPDATE SKIP LOCKED))
        RETURNING id, attempt, at, flow_key, priority
    ), b AS (
        INSERT INTO enqueued (id, attempt, at, flow_key, priority)
        SELECT * FROM d
        RETURNING id, attempt
    ), hist AS (
        INSERT INTO history (id, attempt, kind, instance_id)
        SELECT b.id, b.attempt, 'enqueued', p_instance_id
        FROM b
    )
    SELECT count(*) INTO n FROM b;
    RETURN n;
END $$;

CREATE FUNCTION refresh_stats_v1(p_max_age interval DEFAULT interval '2 seconds') RETURNS boolean
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NOT pg_try_advisory_xact_lock(hashtextextended(current_schema() || '#stats', 0)) THEN
        RETURN false;
    END IF;
    IF EXISTS (SELECT 1 FROM stats WHERE name = 'enqueued' AND at > clock_timestamp() - p_max_age) THEN
        RETURN false;
    END IF;

    INSERT INTO stats (name, value, at)
    SELECT v.name, v.value, clock_timestamp()
    FROM (SELECT count(*) AS n,
                 count(*) FILTER (WHERE flow_key IS NOT NULL) AS held,
                 min(at) FILTER (WHERE flow_key IS NULL) AS due
          FROM enqueued) AS e,
         (SELECT count(*) AS n, count(*) FILTER (WHERE status = 'failed') AS failed
          FROM processed
          WHERE at > now() - interval '24 hours') AS p,
         LATERAL (VALUES
            ('scheduled', (SELECT count(*) FROM scheduled)),
            ('enqueued',  e.n),
            ('held',      e.held),
            ('claimed',   (SELECT count(*) FROM claimed)),
            ('lag_seconds',
                (SELECT coalesce(floor(extract(epoch FROM clock_timestamp() - min(d.at))), 0)::bigint
                 FROM (SELECT e.due AS at
                       UNION ALL
                       SELECT min(s.at) FROM scheduled s WHERE s.at <= clock_timestamp()) d)),
            ('processed_24h', p.n),
            ('failed_24h', p.failed),
            ('instances', (SELECT count(*) FROM instances i WHERE i.stopped_at IS NULL))
         ) AS v(name, value)
    ON CONFLICT (name) DO UPDATE SET value = EXCLUDED.value, at = EXCLUDED.at;
    RETURN true;
END $$;

CREATE FUNCTION claim_plain_v1(p_instance_id text, p_limit int)
RETURNS TABLE (
    id          bigint,
    meta        jsonb,
    headers     jsonb,
    body        bytea,
    schedule_id text,
    key         text,
    attempt     int
)
LANGUAGE sql SET search_path FROM CURRENT AS $$
    WITH b AS (
        DELETE FROM enqueued
        WHERE id = ANY(ARRAY(SELECT e.id
                             FROM enqueued AS e
                             WHERE e.flow_key IS NULL
                             ORDER BY e.priority DESC, e.attempt, e.id
                             LIMIT p_limit
                             FOR UPDATE SKIP LOCKED))
        RETURNING id, attempt, priority
    ), hist AS (
        INSERT INTO history (id, attempt, kind, instance_id)
        SELECT b.id, b.attempt, 'claimed', p_instance_id FROM b
    ), c AS (
        INSERT INTO claimed (id, attempt, priority, instance_id)
        SELECT b.id, b.attempt, b.priority, p_instance_id FROM b
        RETURNING claimed.id, claimed.attempt, claimed.priority
    )
    SELECT j.id, j.meta, j.headers, j.body, j.schedule_id, j.key, c.attempt
    FROM c
    INNER JOIN jobs AS j ON j.id = c.id
    ORDER BY c.priority DESC, c.attempt, c.id
$$;

CREATE FUNCTION flow_rate_free_v1(p_rate int, p_period int, p_next_at timestamptz)
RETURNS int
LANGUAGE sql STABLE PARALLEL SAFE AS $$
    SELECT CASE
        WHEN p_rate IS NULL THEN 2147483647
        ELSE floor(greatest(p_period - greatest(extract(epoch FROM p_next_at - now()), 0), 0)
                   * p_rate / p_period)::int
    END
$$;

CREATE FUNCTION claim_flow_v1(p_instance_id text, p_limit int)
RETURNS TABLE (
    id          bigint,
    meta        jsonb,
    headers     jsonb,
    body        bytea,
    schedule_id text,
    key         text,
    attempt     int
)
LANGUAGE plpgsql SET search_path FROM CURRENT SET jit = off AS $$
#variable_conflict use_column
DECLARE
    v_flows text[];
BEGIN
    WITH RECURSIVE names(flow_key) AS (
        (SELECT e.flow_key FROM enqueued e WHERE e.flow_key IS NOT NULL ORDER BY e.flow_key LIMIT 1)
        UNION ALL
        SELECT (SELECT e.flow_key FROM enqueued e WHERE e.flow_key > names.flow_key ORDER BY e.flow_key LIMIT 1)
        FROM names
        WHERE names.flow_key IS NOT NULL
    ), ready AS MATERIALIZED (
        SELECT names.flow_key
        FROM names
        LEFT JOIN flows f ON f.flow_id = names.flow_key
        WHERE names.flow_key IS NOT NULL
          AND NOT coalesce(f.paused, false)
          AND flow_rate_free_v1(f.rate, f.rate_period, f.next_at) >= 1
          AND (SELECT count(*) FROM claimed c WHERE c.flow_key = names.flow_key) < coalesce(f.concurrency, 1)
    )
    SELECT coalesce(array_agg(l.flow_key), '{}')
    INTO v_flows
    FROM (SELECT ready.flow_key
          FROM ready
          WHERE pg_try_advisory_xact_lock(hashtextextended(current_schema() || ':' || ready.flow_key, 0))
          LIMIT p_limit) l;

    RETURN QUERY
    WITH a AS (
        SELECT x.id
        FROM unnest(v_flows) AS u(name)
        LEFT JOIN flows f ON f.flow_id = u.name
        CROSS JOIN LATERAL (
            SELECT e.id
            FROM enqueued e
            WHERE e.flow_key = u.name
            ORDER BY e.priority DESC, e.attempt, e.id
            LIMIT least(greatest(coalesce(f.concurrency, 1)
                                 - (SELECT count(*) FROM claimed cl WHERE cl.flow_key = u.name), 0),
                        flow_rate_free_v1(f.rate, f.rate_period, f.next_at))
        ) x
        ORDER BY x.id
        LIMIT p_limit
    ), b AS (
        DELETE FROM enqueued WHERE id = ANY(ARRAY(SELECT a.id FROM a)) RETURNING id, attempt, flow_key, priority
    ), hist AS (
        INSERT INTO history (id, attempt, kind, instance_id)
        SELECT b.id, b.attempt, 'claimed', p_instance_id FROM b
    ), rated AS (
        UPDATE flows f
        SET next_at = greatest(f.next_at, now()) + make_interval(secs => f.rate_period::float8 * y.n / f.rate)
        FROM (SELECT b.flow_key, count(*) AS n FROM b GROUP BY b.flow_key) y
        WHERE f.flow_id = y.flow_key AND f.rate IS NOT NULL
    ), c AS (
        INSERT INTO claimed (id, attempt, flow_key, priority, instance_id)
        SELECT b.id, b.attempt, b.flow_key, b.priority, p_instance_id FROM b
        RETURNING claimed.id, claimed.attempt, claimed.priority
    )
    SELECT j.id, j.meta, j.headers, j.body, j.schedule_id, j.key, c.attempt
    FROM c
    INNER JOIN jobs AS j ON j.id = c.id
    ORDER BY c.priority DESC, c.attempt, c.id;
END $$;

CREATE FUNCTION claim_v1(p_instance_id text, p_limit int)
RETURNS TABLE (
    id          bigint,
    meta        jsonb,
    headers     jsonb,
    body        bytea,
    schedule_id text,
    key         text,
    attempt     int
)
LANGUAGE plpgsql SET search_path FROM CURRENT SET jit = off AS $$
DECLARE
    v_plain bigint;
BEGIN
    RETURN QUERY SELECT * FROM claim_plain_v1(p_instance_id, p_limit);
    GET DIAGNOSTICS v_plain = ROW_COUNT;
    IF v_plain < p_limit THEN
        RETURN QUERY SELECT * FROM claim_flow_v1(p_instance_id, p_limit - v_plain::int);
    END IF;
END $$;
