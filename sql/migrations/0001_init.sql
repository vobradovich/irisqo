-- irisqo schema. Runs with search_path = <schema> (irisqo by default):
-- no name below is schema-qualified. Before the migrations the application runs
-- CREATE SCHEMA IF NOT EXISTS <schema> and SET search_path.
--
-- A job lives in exactly one of four state tables:
--   scheduled -> enqueued -> claimed -> processed
-- `at` is the time the row entered its state.

-- # Names and ids
-- Queue, schedule and instance are `text`, a name like 'order-42' (^[a-z0-9][a-z0-9._:-]{0,127}$);
-- a key is any text of 1-255 characters without control characters. They are checked where they
-- come in (API, enqueue_v1), not by a regex CHECK on every write (about 12 us each).

-- # Entities
-- ## Instances
CREATE TABLE instances (
    instance_id text PRIMARY KEY,                     -- host:ulid, in lower case
    roles       text[] NOT NULL                       -- what this process runs
                CHECK (cardinality(roles) > 0
                       AND roles <@ ARRAY['http', 'worker', 'scheduler', 'retention', 'relay']),
    queues      text[] NULL,                          -- worker: queues it serves, NULL = any
    unqueued    boolean NOT NULL DEFAULT true,        -- worker: takes the jobs without a queue
    version     text NOT NULL,                        -- running version
    started_at  timestamptz NOT NULL DEFAULT now(),
    seen_at     timestamptz NOT NULL DEFAULT now(),   -- last heartbeat
    stopped_at  timestamptz NULL                      -- NULL while the instance is live
);

-- ## Queues (Flow Control)
-- Only declared queues and queues with settings. A queue without a row here is dynamic with
-- the defaults: N = 1, ordered, not paused, no rate limit.
CREATE TABLE queues (
    queue_id    text PRIMARY KEY,                   -- 'payments', 'order-42'
    parallelism int NOT NULL DEFAULT 1
                CHECK (parallelism > 0),
    ordered     boolean NOT NULL DEFAULT true,       -- a retry keeps its place in the queue
    rate        int NULL
                CHECK (rate > 0),                    -- runs per rate_period
    rate_period interval NOT NULL DEFAULT '1 second'
                CHECK (rate_period > interval '0'),
    next_at     timestamptz NULL,                    -- rate limit: no job of the queue starts before this
    paused      boolean NOT NULL DEFAULT false
);

-- ## Schedules
-- There is no template: next_id points to the waiting job, which is the template of the next run.
-- The kind follows from `schedule`: digits only is an interval in seconds, otherwise cron.
-- TODO: limit on the number of runs (`until` limits by time only).
CREATE TABLE schedules (
    schedule_id text PRIMARY KEY,                    -- a name: given or generated (petname)
    schedule    text NOT NULL,                       -- '300' or '0 9 * * 1-5'
    timezone    text NOT NULL DEFAULT 'UTC',         -- timezone of a cron schedule
    next_id     bigint NULL,                         -- the waiting run
    next_at     timestamptz NULL,
    until       timestamptz NULL,
    miss_policy text NOT NULL DEFAULT 'run_once'     -- runs missed during downtime:
                CHECK (miss_policy IN ('skip', 'run_once', 'run_all')),   -- none | one now | every one
    paused      boolean NOT NULL DEFAULT false
);

-- ## Jobs: what to run (immutable part)
CREATE TABLE jobs (
    id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at  timestamptz NOT NULL DEFAULT now(),
    meta        jsonb NOT NULL,                      -- target, method, options, queue, priority, sink, callback, then, relation
    headers     jsonb NULL,
    body        bytea NULL,
    key         text NULL,                          -- client idempotency key, unique
    schedule_id text NULL REFERENCES schedules ON DELETE SET NULL,
    parent_id   bigint NULL REFERENCES jobs ON DELETE SET NULL   -- the job this one answers: callback / then / retry_of
);
CREATE UNIQUE INDEX ux_jobs_key     ON jobs (key) WHERE key IS NOT NULL;
CREATE INDEX ix_jobs_schedule_id    ON jobs (schedule_id) WHERE schedule_id IS NOT NULL;
CREATE INDEX ix_jobs_parent_id      ON jobs (parent_id) WHERE parent_id IS NOT NULL;

-- # States
-- 1. scheduled: waits for its time
CREATE TABLE scheduled (
    id       bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    at       timestamptz NOT NULL,                   -- when to run
    retry    int NOT NULL DEFAULT 0
             CHECK (retry >= 0),
    queue    text NULL,                              -- meta.queue, copied to enqueued
    priority smallint NOT NULL DEFAULT 0,            -- meta.priority; higher runs first, copied to enqueued
    CONSTRAINT ck_scheduled_queue_priority CHECK (queue IS NULL OR priority = 0)
);
CREATE INDEX ix_scheduled_at ON scheduled (at);

-- 2. enqueued: its time has come, waits for a worker
-- Queue lag = claim time - at.
--
-- `queue` is meta.queue; NULL means no queue. A job has either a queue or a priority:
-- priority orders only the rows without a queue (a CHECK keeps it 0 in a queue).
-- TODO: --host-parallelism: a job is not limited per target host yet
-- (needs a `host` column in enqueued and claimed).
--
-- Selection (claim_v1), one transaction per batch:
--   Rows without a queue come first: at <= now(), priority DESC, retry ASC (new jobs before
--   retries), id ASC. The queues are tried only when these rows do not fill the batch, so a
--   queue gets what the rows without a queue leave (dedicate a worker to important queues).
--   Queues: up to p_limit queues are locked first with pg_try_advisory_xact_lock (a queue
--   locked by another worker is skipped, a saturated, paused or rate-limited one is not
--   tried), so one worker claims a queue at a time. A queue then gives (parallelism - running)
--   rows in id order, running being its number of `claimed` rows; at most `rate` rows, and
--   nothing before next_at; a claim of n rows sets next_at = now() + rate_period * n / rate.
--   A row of an ordered queue waits for every earlier row of the queue that is held (at > now()).
--   A worker can serve only some jobs: p_unqueued = false skips the rows without a queue,
--   p_queues limits the queues (NULL: any, '{}': none).
--
-- A retry with a delay goes back to `scheduled`, except in an ordered queue: there it stays
-- here with `at` in the future, holds its place, and later jobs of the queue wait for it.
CREATE TABLE enqueued (
    id       bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    retry    int NOT NULL DEFAULT 0
             CHECK (retry >= 0),
    at       timestamptz NOT NULL DEFAULT now(),     -- the earliest moment the job may start
    queue    text NULL,                             -- copied on entry
    priority smallint NOT NULL DEFAULT 0,            -- copied from scheduled or meta.priority
    CONSTRAINT ck_enqueued_queue_priority CHECK (queue IS NULL OR priority = 0)
);
CREATE INDEX ix_enqueued_candidates ON enqueued (priority DESC, retry, id)
    WHERE queue IS NULL;       -- rows without a queue
CREATE INDEX ix_enqueued_queue      ON enqueued (queue, id)
    WHERE queue IS NOT NULL;   -- the window of a queue

-- 3. claimed: running
CREATE TABLE claimed (
    id          bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    retry       int NOT NULL,
    queue       text NULL,
    instance_id text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now()       -- claim time
);
CREATE INDEX ix_claimed_queue       ON claimed (queue) WHERE queue IS NOT NULL;
CREATE INDEX ix_claimed_instance_id ON claimed (instance_id);
CREATE INDEX ix_claimed_at          ON claimed (at);   -- reaper

-- 4. processed: finished, with the response of the target (outcome, headers; the body only with --store-response)
CREATE TABLE processed (
    id          bigint PRIMARY KEY REFERENCES jobs ON DELETE CASCADE,
    retry       int NOT NULL,
    instance_id text NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    status      text NOT NULL
                CHECK (status IN ('completed', 'failed', 'cancelled')),
    outcome     jsonb NULL,   -- HTTP status and version | timeout | error, trace_id/span_id; NULL: cancelled
    headers     jsonb NULL,
    body        bytea NULL
);
CREATE INDEX ix_processed_at        ON processed (at);                -- retention
CREATE INDEX ix_processed_status_id ON processed (status, id DESC);   -- UI tabs

-- ## History
-- Journal of state changes. seq is the cursor for the indexer (Quickwit / OpenObserve):
-- rows are written in the same transaction as the state change, so this is an outbox.
CREATE TABLE history (
    seq         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id          bigint NOT NULL REFERENCES jobs ON DELETE CASCADE,
    retry       int NOT NULL,
    at          timestamptz NOT NULL DEFAULT now(),
    kind        text NOT NULL
                CHECK (kind IN ('scheduled', 'enqueued', 'claimed', 'released', 'retried',
                                'completed', 'failed', 'cancelled', 'callback')),
    instance_id text NULL,
    message     text NULL
);
CREATE INDEX ix_history_id_seq ON history (id, seq);

-- ## Stats
-- The counters of the UI, counted once per refresh_stats_v1 instead of once per page request.
--   scheduled, enqueued, claimed   rows in the state tables
--   lag_seconds                    age of the oldest due job that has not started
--   processed_24h, failed_24h      finished in the last 24 hours
--   instances                      live instances
CREATE TABLE stats (
    name  text PRIMARY KEY,
    value bigint NOT NULL,
    at    timestamptz NOT NULL    -- when it was counted
) WITH (fillfactor = 50);         -- a few rows rewritten all the time: room for HOT updates

-- # Functions
-- ## enqueue_v1
-- Enqueue inside the caller's transaction (embedded mode). Returns the job id.
-- job is a JSON object, only `url` is required:
--   url           http(s) URL of the target
--   method        default POST
--   headers       object of strings
--   body          text; body_base64 for binary
--   at | delay    not before this unix time | after this number of seconds
--   timeout       milliseconds, default 30000
--   retry         none (default) | immediate | fixed | fibonacci, with retry_count (up to 9999)
--                 and, for fixed and fibonacci, retry_delay in seconds (up to 99999)
--   queue | priority   either one: priority orders only the jobs without a queue
--   key           idempotency key: a repeated key returns the existing job id
--   traceparent, tracestate
-- Only the format is checked: the target is not (no DNS, no private-address check). The
-- columns check the rest: the range of priority (smallint), a queue together with a priority.
-- Schedules are not created here.
CREATE FUNCTION enqueue_v1(job jsonb) RETURNS bigint
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_retry    text := coalesce(job->>'retry', 'none');
    v_queue    text := nullif(job->>'queue', '');
    v_key      text := nullif(job->>'key', '');
    v_priority smallint;
    v_timeout  int;
    v_body     bytea;
    v_at       timestamptz;
    v_delay    int;
    v_meta     jsonb;
    v_error    text;
    new_id     bigint;
BEGIN
    v_error := CASE
        WHEN jsonb_typeof(job) IS DISTINCT FROM 'object'
            THEN 'must be a JSON object'
        WHEN coalesce(job->>'url', '') !~* '^https?://[^/?#[:space:]]+'
            OR job->>'url' ~ '[[:space:][:cntrl:]]'
            THEN 'url must be an http or https URL without spaces'
        WHEN coalesce(job->>'method', 'POST') !~* '^[a-z]{1,16}$'
            THEN 'method must be an HTTP method'
        WHEN jsonb_typeof(job->'headers') NOT IN ('object', 'null')
            THEN 'headers must be an object'
        WHEN EXISTS (SELECT 1
                     FROM jsonb_each(coalesce(nullif(job->'headers', 'null'::jsonb), '{}')) h
                     WHERE jsonb_typeof(h.value) <> 'string')
            THEN 'header values must be strings'
        WHEN jsonb_typeof(job->'body') = 'string' AND jsonb_typeof(job->'body_base64') = 'string'
            THEN 'body and body_base64 are exclusive'
        WHEN v_key !~ '^[^[:cntrl:]]{1,255}$'
            THEN 'key must be 1 to 255 characters without control characters'
        WHEN v_queue !~ '^[a-z0-9][a-z0-9._:-]{0,127}$'
            THEN 'queue must be 1 to 128 characters of a-z, 0-9, . _ : - and start with a letter or a digit'
        WHEN job->>'priority' !~ '^-?[0-9]{1,5}$'
            THEN 'priority must be an integer'
        WHEN job->>'timeout' !~ '^[1-9][0-9]{0,8}$'
            THEN 'timeout must be a positive number of milliseconds'
        WHEN v_retry NOT IN ('none', 'immediate', 'fixed', 'fibonacci')
            THEN 'retry must be none, immediate, fixed or fibonacci'
        WHEN coalesce(job->>'retry_count', CASE WHEN v_retry <> 'none' THEN '' END) !~ '^[0-9]{1,4}$'
            THEN 'retry_count must be a number up to 9999'
        WHEN coalesce(job->>'retry_delay', CASE WHEN v_retry IN ('fixed', 'fibonacci') THEN '' END) !~ '^[0-9]{1,5}$'
            THEN 'retry_delay must be a number of seconds up to 99999'
        WHEN job->>'at' IS NOT NULL AND job->>'delay' IS NOT NULL
            THEN 'at and delay are exclusive'
        WHEN job->>'at' !~ '^[0-9]{1,12}$'
            THEN 'at must be a unix time in seconds'
        WHEN job->>'delay' !~ '^[0-9]{1,9}$'
            THEN 'delay must be a number of seconds'
    END;
    IF v_error IS NOT NULL THEN
        RAISE EXCEPTION 'invalid job: %', v_error USING ERRCODE = 'invalid_parameter_value';
    END IF;

    v_priority := coalesce((job->>'priority')::smallint, 0);
    v_timeout  := coalesce((job->>'timeout')::int, 30000);
    v_body     := nullif(CASE
                      WHEN jsonb_typeof(job->'body') = 'string' THEN convert_to(job->>'body', 'UTF8')
                      WHEN jsonb_typeof(job->'body_base64') = 'string' THEN decode(job->>'body_base64', 'base64')
                  END, ''::bytea);
    v_at       := CASE
                      WHEN job->>'at' IS NOT NULL THEN to_timestamp((job->>'at')::bigint)
                      WHEN job->>'delay' IS NOT NULL THEN clock_timestamp() + make_interval(secs => (job->>'delay')::int)
                  END;
    IF v_at <= clock_timestamp() THEN
        v_at := NULL;   -- a time in the past runs the job now
    END IF;
    v_delay := ceil(extract(epoch FROM v_at - clock_timestamp()))::int;   -- NULL when there is no delay

    -- same shape as the job meta written by the service
    v_meta := jsonb_strip_nulls(jsonb_build_object(
        'sink', 'http',
        'method', upper(coalesce(job->>'method', 'POST')),
        'url', job->>'url',
        'retry', v_retry,
        'retry_count', CASE WHEN v_retry <> 'none' THEN (job->>'retry_count')::int END,
        'retry_delay', CASE WHEN v_retry IN ('fixed', 'fibonacci') THEN (job->>'retry_delay')::int END,
        'delay', v_delay,
        'timeout', v_timeout,
        'queue', v_queue,
        'priority', nullif(v_priority, 0),
        'traceparent', job->>'traceparent',
        'tracestate', job->>'tracestate'));

    INSERT INTO jobs (meta, headers, body, key)
    VALUES (v_meta, nullif(job->'headers', 'null'::jsonb), v_body, v_key)
    ON CONFLICT (key) WHERE key IS NOT NULL DO NOTHING
    RETURNING jobs.id INTO new_id;
    IF new_id IS NULL THEN   -- the key exists: idempotent repeat
        RETURN (SELECT j.id FROM jobs j WHERE j.key = v_key);
    END IF;

    IF v_at IS NULL THEN
        INSERT INTO enqueued (id, queue, priority) VALUES (new_id, v_queue, v_priority);
        INSERT INTO history (id, retry, kind) VALUES (new_id, 0, 'enqueued');
        PERFORM pg_notify(current_schema() || '_enqueued', new_id::text);  -- delivered at COMMIT
    ELSE
        INSERT INTO scheduled (id, at, queue, priority) VALUES (new_id, v_at, v_queue, v_priority);
        INSERT INTO history (id, retry, kind) VALUES (new_id, 0, 'scheduled');
    END IF;
    RETURN new_id;
END $$;

-- ## promote_v1
-- Move up to p_limit due jobs: scheduled -> enqueued, in one transaction. The oldest due
-- come first; `at` is kept, so the queue lag counts from the moment the job was due.
-- Returns the number of jobs moved; workers are woken once per non-empty batch.
CREATE FUNCTION promote_v1(p_instance_id text, p_limit int) RETURNS int
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    n int;
BEGIN
    WITH d AS (
        DELETE FROM scheduled
        WHERE id IN (SELECT s.id
                     FROM scheduled s
                     WHERE s.at <= now()
                     ORDER BY s.at, s.id
                     LIMIT p_limit
                     FOR UPDATE SKIP LOCKED)
        RETURNING id, retry, at, queue, priority
    ), b AS (
        INSERT INTO enqueued (id, retry, at, queue, priority)
        SELECT * FROM d
        RETURNING id, retry
    ), hist AS (
        INSERT INTO history (id, retry, kind, instance_id)
        SELECT b.id, b.retry, 'enqueued', p_instance_id
        FROM b
    )
    SELECT count(*) INTO n FROM b;
    IF n > 0 THEN
        PERFORM pg_notify(current_schema() || '_enqueued', '');
    END IF;
    RETURN n;
END $$;

-- ## refresh_stats_v1
-- Recount `stats` unless it is younger than p_max_age. Any process may call it before it
-- reads `stats` (every UI request does): one advisory lock lets one caller count while the
-- others read the old numbers. Returns true when this call counted.
CREATE FUNCTION refresh_stats_v1(p_max_age interval DEFAULT interval '2 seconds') RETURNS boolean
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF NOT pg_try_advisory_xact_lock(hashtextextended(current_schema() || '#stats', 0)) THEN
        RETURN false;
    END IF;
    -- after the lock: the previous holder may have counted just now
    IF EXISTS (SELECT 1 FROM stats WHERE name = 'enqueued' AND at > clock_timestamp() - p_max_age) THEN
        RETURN false;
    END IF;

    INSERT INTO stats (name, value, at)
    SELECT v.name, v.value, clock_timestamp()
    FROM (VALUES
        ('scheduled', (SELECT count(*) FROM scheduled)),
        ('enqueued',  (SELECT count(*) FROM enqueued)),
        ('claimed',   (SELECT count(*) FROM claimed)),
        ('lag_seconds',
            (SELECT coalesce(floor(extract(epoch FROM clock_timestamp() - min(d.at))), 0)::bigint
             FROM (SELECT min(e.at) AS at FROM enqueued e WHERE e.at <= clock_timestamp()
                   UNION ALL
                   SELECT min(s.at) FROM scheduled s WHERE s.at <= clock_timestamp()) d)),
        ('processed_24h',
            (SELECT count(*) FROM processed p WHERE p.at > now() - interval '24 hours')),
        ('failed_24h',
            (SELECT count(*) FROM processed p
             WHERE p.at > now() - interval '24 hours' AND p.status = 'failed')),
        ('instances', (SELECT count(*) FROM instances i WHERE i.stopped_at IS NULL))
    ) AS v(name, value)
    ON CONFLICT (name) DO UPDATE SET value = EXCLUDED.value, at = EXCLUDED.at;
    RETURN true;
END $$;

-- ## claim_v1
-- Claim up to p_limit jobs for a worker: enqueued -> claimed, in one transaction.
-- Selection rules: see the comment above `enqueued`. A worker can serve only some jobs:
-- p_unqueued = false skips the jobs without a queue; p_queues limits the queues
-- (NULL: any queue, '{}': none). The caller joins jobs by id:
--   SELECT j.*, c.retry FROM claim_v1($1, $2) c JOIN jobs j USING (id)
-- jit is off: the planner overestimates the cost of the queue part, and JIT compilation
-- then took about 250 ms per call.
CREATE FUNCTION claim_v1(
    p_instance_id text,
    p_limit       int,
    p_unqueued    boolean DEFAULT true,
    p_queues      text[]  DEFAULT NULL
)
RETURNS TABLE (id bigint, retry int)
-- ROWS: without it the planner assumes 1000 rows and joins the result with `jobs` by a seq scan of jobs
ROWS 64
LANGUAGE plpgsql SET search_path FROM CURRENT SET jit = off AS $$
#variable_conflict use_column
DECLARE
    v_queues text[] := '{}';   -- queues locked for this batch
BEGIN
    -- Step 1: lock the queues. Skipped (the fast path) when the rows without a queue
    -- already fill the batch. The locks are taken in a statement of their own: the next
    -- statement reads `claimed` after them, so two workers never fill the same free slot.
    -- A queue without a row in `queues` has the defaults.
    IF NOT (
        p_unqueued
        AND (SELECT count(*)
             FROM (SELECT 1
                   FROM enqueued e
                   WHERE e.queue IS NULL AND e.at <= now()
                   LIMIT p_limit) f) >= p_limit
    ) THEN
        WITH RECURSIVE qs(queue) AS (   -- distinct waiting queues (index skip scan)
            (SELECT e.queue
             FROM enqueued e
             WHERE p_queues IS NULL AND e.queue IS NOT NULL
             ORDER BY e.queue
             LIMIT 1)
            UNION ALL
            SELECT (SELECT e.queue
                    FROM enqueued e
                    WHERE e.queue > qs.queue
                    ORDER BY e.queue
                    LIMIT 1)
            FROM qs
            WHERE qs.queue IS NOT NULL
        ), src AS (   -- the waiting queues, or the ones this worker serves
            SELECT qs.queue FROM qs WHERE qs.queue IS NOT NULL
            UNION ALL
            SELECT u FROM unnest(p_queues) AS u
        ), ready AS MATERIALIZED (   -- a queue that can give a job right now
            SELECT src.queue
            FROM src
            LEFT JOIN queues q ON q.queue_id = src.queue
            WHERE NOT coalesce(q.paused, false)
              AND (q.next_at IS NULL OR q.next_at <= now())
              AND EXISTS (SELECT 1
                          FROM enqueued e
                          WHERE e.queue = src.queue AND e.at <= now())
              AND (SELECT count(*)
                   FROM claimed c
                   WHERE c.queue = src.queue) < coalesce(q.parallelism, 1)
        )
        SELECT coalesce(array_agg(l.queue), '{}')
        INTO v_queues
        FROM (SELECT ready.queue
              FROM ready
              WHERE pg_try_advisory_xact_lock(hashtextextended(current_schema() || ':' || ready.queue, 0))
              LIMIT p_limit) l;
    END IF;

    -- Step 2: take the rows.
    RETURN QUERY
    WITH a AS (
        -- rows without a queue: new jobs before retries
        SELECT u.id, u.retry, u.priority, false AS queued
        FROM (SELECT e.id, e.retry, e.priority
              FROM enqueued e
              WHERE p_unqueued AND e.queue IS NULL AND e.at <= now()
              ORDER BY e.priority DESC, e.retry, e.id
              LIMIT p_limit
              FOR UPDATE SKIP LOCKED) u
        UNION ALL
        -- locked queues: free slots, in id order; an ordered queue waits for a held row
        (SELECT s.id, s.retry, s.priority, true
         FROM unnest(v_queues) AS u(name)
         LEFT JOIN queues q ON q.queue_id = u.name
         CROSS JOIN LATERAL (
             SELECT e.id, e.retry, e.priority
             FROM enqueued e
             WHERE e.queue = u.name
               AND e.at <= now()
               -- the queue may have been paused or rate limited since the first step
               AND NOT coalesce(q.paused, false)
               AND (q.next_at IS NULL OR q.next_at <= now())
               AND (NOT coalesce(q.ordered, true)
                    OR NOT EXISTS (SELECT 1
                                   FROM enqueued h
                                   WHERE h.queue = u.name AND h.id < e.id AND h.at > now()))
             ORDER BY e.id
             LIMIT least(
                 greatest(coalesce(q.parallelism, 1)
                          - (SELECT count(*) FROM claimed c WHERE c.queue = u.name), 0),
                 coalesce(q.rate, 2147483647))
         ) s)
    ), b AS (
        DELETE FROM enqueued
        WHERE id IN (SELECT a.id
                     FROM a
                     -- a queue gives its rows in id order, whatever their retry
                     ORDER BY a.queued, a.priority DESC, CASE WHEN a.queued THEN 0 ELSE a.retry END, a.id
                     LIMIT p_limit)
        RETURNING id, retry, queue
    ), hist AS (
        INSERT INTO history (id, retry, kind, instance_id)
        SELECT b.id, b.retry, 'claimed', p_instance_id
        FROM b
    ), rated AS (
        UPDATE queues q
        SET next_at = now() + q.rate_period * x.n / q.rate
        FROM (SELECT b.queue, count(*) AS n
              FROM b
              GROUP BY b.queue) x
        WHERE q.queue_id = x.queue AND q.rate IS NOT NULL
    )
    INSERT INTO claimed (id, retry, queue, instance_id)
    SELECT b.id, b.retry, b.queue, p_instance_id
    FROM b
    RETURNING claimed.id, claimed.retry;
END $$;
